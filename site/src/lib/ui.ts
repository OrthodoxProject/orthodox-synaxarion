/** UI string with {placeholders} filled in. */
export function t(lang: Lang, key: UiKey, values: Record<string, string | number> = {}): string {
  return UI[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

